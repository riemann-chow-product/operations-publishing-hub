export const CATEGORY_MAP: Record<CategoryId, WordCategory> = CATEGORIES.reduce(
  (acc, category) => {
    acc[category.id] = category
    return acc
  },
  {} as Record<CategoryId, WordCategory>,
)

export function getActiveCategories(platform: PlatformId, hasCustomWords: boolean): WordCategory[] {
  return CATEGORIES.filter((category) => {
    if (category.id === 'custom') return hasCustomWords
    return category.platforms.includes(platform)
  })
}

